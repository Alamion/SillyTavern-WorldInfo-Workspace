import { useState } from 'react';
import type { ImageCaption } from '../../adapters/imageCaption';
import type { ProfileInfo } from '../../core/assistant/ports';
import { PROMPT_CONTEXT_RANGE, type ImageSettings } from '../../core/images/settings';
import { FormField, FormSection, MenuPanel, NumberField } from '../formControls';

/**
 * Image settings (spec 009 contracts/ui-contract.md): which connection profile
 * and model write captions and prompt drafts. Pictures themselves follow the
 * Image Generation extension's settings.
 */
export function ImageSettingsPanel({
    caption,
    profiles,
    assistantProfileName,
    onClose,
}: {
    caption: ImageCaption;
    profiles: ProfileInfo[];
    assistantProfileName: string | null;
    onClose: () => void;
}): JSX.Element {
    const [settings, setSettings] = useState<ImageSettings>(() => caption.settings());
    const [locked, setLocked] = useState(false);
    const update = (patch: Partial<ImageSettings>): void => {
        if (caption.updateSettings(patch)) {
            setSettings(caption.settings());
        } else {
            setLocked(true);
        }
    };
    const chatProfiles = profiles.filter((profile) => profile.api === 'chat-completion');
    const missing = (id: string | null): boolean => id !== null && !profiles.some((profile) => profile.id === id);

    return (
        <MenuPanel
            title="Image settings"
            footerHint="Pictures are generated by the Image Generation extension with its own settings."
            onClose={onClose}
        >
            {locked && (
                <p className="wiw-banner wiw-banner-warn">
                    Settings can be changed after the workspace recovery banner is resolved.
                </p>
            )}
            <FormSection
                title="Captions"
                hint="A Chat Completion profile whose model can read pictures (e.g. google/gemma-3-12b-it on OpenRouter)."
            >
                <FormField label="Profile">
                    <select
                        value={settings.captionProfileId ?? ''}
                        disabled={locked}
                        onChange={(event) => update({ captionProfileId: event.target.value === '' ? null : event.target.value })}
                    >
                        <option value="">None — choose a profile</option>
                        {missing(settings.captionProfileId) && <option value={settings.captionProfileId ?? ''}>(deleted profile)</option>}
                        {chatProfiles.map((profile) => (
                            <option key={profile.id} value={profile.id}>
                                {profile.name}
                            </option>
                        ))}
                    </select>
                </FormField>
                <FormField label="Model" hint="Empty = the profile's model">
                    <input
                        type="text"
                        placeholder="Profile's model"
                        defaultValue={settings.captionModel}
                        disabled={locked}
                        onBlur={(event) => update({ captionModel: event.target.value })}
                    />
                </FormField>
                <FormField label="Instruction">
                    <textarea
                        rows={3}
                        defaultValue={settings.captionInstruction}
                        disabled={locked}
                        onBlur={(event) => update({ captionInstruction: event.target.value })}
                    />
                </FormField>
            </FormSection>
            <FormSection title="Prompt drafting" hint="Writes picture prompts from the lore entries next to an image.">
                <FormField label="Profile">
                    <select
                        value={settings.promptProfileId ?? ''}
                        disabled={locked}
                        onChange={(event) => update({ promptProfileId: event.target.value === '' ? null : event.target.value })}
                    >
                        <option value="">
                            Same as the assistant{assistantProfileName ? ` (${assistantProfileName})` : ''}
                        </option>
                        {missing(settings.promptProfileId) && <option value={settings.promptProfileId ?? ''}>(deleted profile)</option>}
                        {profiles.map((profile) => (
                            <option key={profile.id} value={profile.id}>
                                {profile.name}
                            </option>
                        ))}
                    </select>
                </FormField>
                <div className="wiw-form-row">
                    <FormField label="Model" hint="Empty = the profile's model">
                        <input
                            type="text"
                            placeholder="Profile's model"
                            defaultValue={settings.promptModel}
                            disabled={locked}
                            onBlur={(event) => update({ promptModel: event.target.value })}
                        />
                    </FormField>
                    <NumberField
                        label="Lore size (tokens)"
                        value={settings.promptContextTokens}
                        min={PROMPT_CONTEXT_RANGE.min}
                        max={PROMPT_CONTEXT_RANGE.max}
                        disabled={locked}
                        onCommit={(value) => update({ promptContextTokens: value })}
                    />
                </div>
                <FormField label="Instruction">
                    <textarea
                        rows={4}
                        defaultValue={settings.promptInstruction}
                        disabled={locked}
                        onBlur={(event) => update({ promptInstruction: event.target.value })}
                    />
                </FormField>
            </FormSection>
        </MenuPanel>
    );
}
